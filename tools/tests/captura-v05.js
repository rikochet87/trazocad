doc.begin(); doc.params.push({ name: 'ancho', expr: '80' }); doc.commit();
out.d1 = await cmd('DCHORIZONTAL', '', pick(A, { x: 50, y: 0 }), '50,-15', 'ancho*1.5');
out.d2 = await cmd('DCVERTICAL', '', pick(B, { x: 100, y: 27 }), '135,30', 'd1/2');
