await cmd('GCVERTICAL', '', pick(B, { x: 99.5, y: 27 }));
await cmd('GCPARALLEL', pick(A, { x: 50, y: 1.5 }), pick(C, { x: 50, y: 50 }));
await cmd('GCPERPENDICULAR', pick(A, { x: 50, y: 1.5 }), pick(D, { x: -1, y: 25 }));
